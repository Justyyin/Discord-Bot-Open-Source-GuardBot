"""Write docs/REFERENCE.md, the list of every slash command with its options, generated from the real commands.

Usage: python scripts/build_reference.py          write the file
       python scripts/build_reference.py --check  exit with 1 when the file is out of date
"""

import asyncio
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from guardbot import layout  # noqa: E402
from guardbot.core import EXTENSIONS, Bot  # noqa: E402

TARGET = ROOT / "docs" / "REFERENCE.md"


async def build():
    """Return the text of the reference, built from a bot with every cog loaded."""
    bot = Bot({"data_dir": tempfile.mkdtemp()})

    async def never_ready():
        await asyncio.Event().wait()

    bot.wait_until_ready = never_ready
    for ext in EXTENSIONS:
        await bot.load_extension(f"guardbot.cogs.{ext}")
    bot.arrange_commands()
    rows = {}

    def walk(cmd, prefix=""):
        if hasattr(cmd, "commands"):
            for sub in cmd.commands:
                walk(sub, prefix + cmd.name + " ")
        else:
            options = ", ".join(("`%s`" % p.name) if p.required else ("`%s`?" % p.name) for p in cmd.parameters)
            rows[(prefix + cmd.name)] = (cmd.description, options)

    for root in bot.tree.get_commands():
        if hasattr(root, "parameters") or hasattr(root, "commands"):
            walk(root)
    lines = [
        "# Command reference",
        "",
        "This file is generated by `python scripts/build_reference.py`. Do not edit it by hand. An option with a question mark is optional.",
        "",
    ]
    for key, (desc, _) in layout.GROUPS.items():
        lines += ["## /%s" % key, "", desc + ".", "", "| Command | Description | Options |", "| --- | --- | --- |"]
        for path in sorted(p for p in rows if p.split()[0] == key):
            d, o = rows[path]
            lines.append("| `/%s` | %s | %s |" % (path, d.replace("|", "/"), o))
        lines.append("")
    loose = sorted(p for p in rows if p.split()[0] not in layout.GROUPS)
    lines += ["## Other commands", "", "| Command | Description | Options |", "| --- | --- | --- |"]
    for path in loose:
        d, o = rows[path]
        lines.append("| `/%s` | %s | %s |" % (path, d.replace("|", "/"), o))
    lines.append("")
    for cog in list(bot.cogs):
        await bot.remove_cog(cog)
    bot.store.close()
    return "\n".join(lines)


def main():
    """Write or check the file."""
    text = asyncio.run(build())
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("docs/REFERENCE.md is out of date. Run python scripts/build_reference.py")
            sys.exit(1)
        print("up to date")
        return
    TARGET.write_text(text, encoding="utf-8")
    print("written", TARGET.relative_to(ROOT), len(text.splitlines()), "lines")


if __name__ == "__main__":
    main()
